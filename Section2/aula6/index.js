/*
Exemplos de Uso
1. Uso do let (Valores Mutáveis)
Use let quando o valor da variável precisar mudar ao longo do ciclo de vida do programa, como em contadores, acumuladores ou reatribuições diretas.

*/

// o valor inicial pode ser o reatribuido 
let contador = 0; 
contador = +1;
console.log(contador); // output: 1 

